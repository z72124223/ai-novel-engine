    private fun scenario(number: Int, seed: Seed): NpcActorHardBlindScenario {
        val id = "npc-actor02-%02d".format(number)
        val targetId = "interlocutor-$id"
        return NpcActorHardBlindScenario(
            scenarioId = id,
            title = seed.title,
            category = seed.category,
            actorId = seed.actorId,
            actorSpeakerId = seed.actorId,
            reviewerCharacterBrief = seed.characterBrief,
            sceneContext = seed.sceneContext,
            actorOwnedEvidence = listOf(
                NpcActorEvidenceRef(
                    evidenceId = "profile-$id",
                    kind = "PROFILE",
                    summary = seed.characterBrief,
                    visibility = "ACTOR_OWNED",
                ),
                NpcActorEvidenceRef(
                    evidenceId = "scene-$id",
                    kind = "PERCEPTION",
                    summary = seed.sceneContext,
                    visibility = "ACTOR_VISIBLE",
                ),
            ),
            forbiddenEvidence = listOf(
                NpcActorEvidenceRef(
                    evidenceId = "author-secret-$id",
                    kind = "AUTHOR_SECRET",
                    summary = seed.forbiddenToken,
                    visibility = "AUTHOR_ONLY",
                ),
            ),
            sharedOpeningTurns = listOf(
                turn(targetId, seed.targetLabel, seed.openingLine),
            ),
            naturalControlCandidate = NpcActorHardBlindCandidate(
                sourceType = "NATURAL_CONTROL_FIXTURE",
                turns = listOf(
                    turn(seed.actorId, seed.actorLabel, seed.controlLine1, seed.controlAction1),
                    turn(targetId, seed.targetLabel, seed.followUpLine),
                    turn(seed.actorId, seed.actorLabel, seed.controlLine2, seed.controlAction2),
                ),
            ),
            actorProfileCandidate = NpcActorHardBlindCandidate(
                sourceType = "ACTOR_PROFILE_FIXTURE",
                turns = listOf(
                    turn(seed.actorId, seed.actorLabel, seed.actorLine1, seed.actorAction1),
                    turn(targetId, seed.targetLabel, seed.followUpLine),
                    turn(seed.actorId, seed.actorLabel, seed.actorLine2, seed.actorAction2),
                ),
            ),
            ratingDimensions = listOf(
                "NATURALNESS",
                "VOICE_CONSISTENCY",
                "MOTIVE_COHERENCE",
                "KNOWLEDGE_BOUNDARY",
                "CONTINUITY",
                "MULTI_TURN_REPAIR",
            ),
        )
    }

